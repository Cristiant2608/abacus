// The same tested decimal/pagination core runs in React Native and Scriptable.
const fs = require('fs');
const ts = require('typescript');

const compiled = ts.transpileModule(fs.readFileSync('src/lib/finance-summary.ts', 'utf8'), {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS },
}).outputText;
const runtime = fs.readFileSync('integrations/scriptable/runtime.js', 'utf8').trimEnd();
const script = `/* eslint-disable */\n// Generated by scripts/generate-scriptable-widget.cjs. No credentials included.\nconst AbacusFinance = (() => { const exports = {};\n${compiled}\nreturn exports; })();\n${runtime}\n`;
const outputs = {
  'integrations/scriptable/abacus-widget.js': script,
  'src/lib/scriptable-widget-source.ts': `/* eslint-disable */\n// Generated by scripts/generate-scriptable-widget.cjs; contains no credentials.\nconst scriptableWidgetSource = ${JSON.stringify(script)};\nexport default scriptableWidgetSource;\n`,
};
Object.entries(outputs).forEach(([path, content]) => {
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(path, 'utf8') !== content) throw new Error(`Regenerate ${path} with node scripts/generate-scriptable-widget.cjs`);
  } else fs.writeFileSync(path, content);
});
